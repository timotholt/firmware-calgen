"""Turn a successful Build into C: a standalone header, or patches to marked blocks.

Output is deterministic: no timestamps, fixed ordering, ASCII only, ``\\n`` line
endings. The same inputs always produce byte-identical files, so a diff shows
only real changes.
"""

from __future__ import annotations

import re
import textwrap

from calgen import __version__
from calgen.build import OK, SKIPPED, Build, ConstResult, Source
from calgen.units import from_si

_ASCII = str.maketrans({"·": "-", "±": "+/-", "–": "-", "—": "-", "“": '"', "”": '"', "’": "'", "×": "x", "°": " deg", "Ω": "ohm", "µ": "u"})


class GateError(RuntimeError):
    """Generation refused because the build has failures."""

    def __init__(self, failures: list[str]):
        self.failures = failures
        super().__init__("refusing to generate: " + "; ".join(failures))


def ascii_text(text: str) -> str:
    text = text.translate(_ASCII).replace("*/", "* /")
    return text.encode("ascii", "replace").decode("ascii")


def _fmt_num(x: float) -> str:
    return f"{x:.6g}"


def _source_line(s: Source) -> str:
    if isinstance(s.value, str):
        shown = s.value
    else:
        shown = f"{_fmt_num(from_si(s.value.value, s.unit or '1'))} {s.unit or ''}".strip()
    where = s.origin
    if s.quote and s.name.startswith("ds."):
        quote = s.quote if len(s.quote) <= 60 else s.quote[:57] + "..."
        where += f': "{quote}"'
    return ascii_text(f"{s.name} = {shown}  [{where}]")


def _value_note(c: ConstResult) -> str:
    e = c.encoded
    parts = [f"{_fmt_num(e.stored)} {c.rule.unit}"]
    if c.fmt != "float32":
        parts.append(c.fmt)
    if e.rel_error > 0 and c.fmt != "float32":
        parts.append(f"err {e.rel_error * 100:.2g}%")
    return ", ".join(parts)


def define_block(c: ConstResult) -> list[str]:
    """Comment + #define lines for one constant (empty for constants not generated)."""
    r = c.rule
    lines = [f"/* {ascii_text(r.describe or r.id)}"]
    if r.kind == "enum":
        lines.append(f" * = {r.formula}")
    else:
        lines.append(f" * = {ascii_text(r.formula)}")
    lines += [f" *   {_source_line(s)}" for s in c.sources if not s.origin == "constant"]
    if r.supplied:
        lines.append(" *   engineer-supplied value, carried through unchanged")
    if c.status == SKIPPED:
        lines.append(f" *   NOT GENERATED: {ascii_text(c.message)}")
        lines[-1] += " */"
        return lines
    lines[-1] += " */"
    if r.kind == "enum":
        lines.append(f"#define {r.symbol:<26} {c.enum_ident}")
    else:
        lines.append(f"#define {r.symbol:<26} {c.encoded.literal:<14} /* {ascii_text(_value_note(c))} */")
    return lines


def _designed_against(build: Build) -> dict[str, str]:
    """design.* params that declare what they were designed against -> 'name = value' text."""
    out = {}
    for p in build.variant.design.params.values():
        if p.designed_against:
            out[f"design.{p.name}"] = ", ".join(f"{k} = {v}" for k, v in sorted(p.designed_against.items()))
    return out


def sections(build: Build) -> dict[str, str]:
    """Generated C text per block id, in rules order."""
    if not build.ok:
        raise GateError(build.failures)
    against = _designed_against(build)
    out: dict[str, list[str]] = {b: [] for b in build.rules.blocks}
    for c in build.constants:
        if c.status not in (OK, SKIPPED):  # pragma: no cover - guarded by build.ok
            continue
        lines = define_block(c)
        if c.rule.supplied:
            for s in c.sources:
                if s.name in against:
                    lines.insert(-1, f"/*   designed against: {ascii_text(against[s.name])} (staleness-tracked) */")
        if out[c.rule.block]:
            out[c.rule.block].append("")
        out[c.rule.block].extend(lines)
    return {b: "\n".join(v) for b, v in out.items() if v}


def guard(variant_name: str) -> str:
    return "CALGEN_" + re.sub(r"[^A-Za-z0-9]", "_", variant_name).upper() + "_H"


def header(build: Build) -> str:
    v = build.variant
    ds = v.datasheet
    secs = sections(build)
    model = ds.params.get("model_string")
    ref = ds.params["part_number"].source.split(" p")[0]
    lines = [
        f"/* GENERATED by calgen {__version__} -- DO NOT EDIT. Regenerate from the spec files.",
        " *",
        f" * variant : {ascii_text(v.name)}",
        f" * product : {ascii_text(ds.part)}  {ascii_text(str(model.value) if model else '')}",
        f" *           ratings from {ascii_text(ref)} (public IntelliPower data sheet)",
        f" * board   : {ascii_text(v.board.name)} rev {ascii_text(str(v.board.extra.get('rev', '?')))}",
        f" * target  : {ascii_text(v.target.name)} (default format {v.target.extra.get('default_format', 'float32')})",
        f" * inputs  : sha256 {build.digest}",
    ]
    if v.overrides:
        lines.append(" *")
        for p in v.overrides.values():
            reason = ascii_text(" ".join(p.note.split()))
            wrapped = textwrap.wrap(f"OVERRIDE ds.{p.name}: {reason}", 76, subsequent_indent="  ")
            lines += [f" * {w}" for w in wrapped]
    lines += [
        " *",
        " * SYNTHETIC DEMO: firmware names and circuit values are invented; product ratings",
        " * come from the public data sheet cited above. Not from any vendor SDK.",
        " */",
        f"#ifndef {guard(v.name)}",
        f"#define {guard(v.name)}",
        "",
    ]
    fmt = str(v.target.extra.get("default_format", "float32"))
    lines += ['#include "calgen_types.h"', ""]
    # The number type and conversions live in this header, not calgen_types.h, so
    # include order cannot change them; mixing two formats in one file fails to compile.
    if fmt.startswith("iq"):
        q = int(fmt[2:])
        lines += [
            f"#define CALGEN_GLOBAL_Q {q}  /* fixed-point target: values below are IQ{q} integers */",
            f"typedef calgen_iq_t calgen_num_t;  /* measurements are compared as IQ{q} integers, no float */",
            f"#define CALGEN_NUM(x)  ((calgen_num_t)((x) * {float(1 << q):.1f}))  /* constant expressions only */",
            f"#define CALGEN_REAL(x) ((float)(x) / {float(1 << q):.1f}f)  /* host-side checks only */",
        ]
    else:
        lines += [
            "typedef float calgen_num_t;  /* float target */",
            "#define CALGEN_NUM(x)  ((calgen_num_t)(x))",
            "#define CALGEN_REAL(x) ((float)(x))",
        ]
    for block_id, title in build.rules.blocks.items():
        if block_id not in secs:
            continue
        rule = "=" * max(4, 70 - len(title))
        lines += ["", f"/* ==== {ascii_text(title)} {rule} */", "", secs[block_id]]
    lines += ["", f"#endif /* {guard(v.name)} */", ""]
    return "\n".join(lines)


_BEGIN = re.compile(r"^[ \t]*/\* CALGEN:BEGIN (\w+) \*/[ \t]*$", re.M)
_END = re.compile(r"^[ \t]*/\* CALGEN:END (\w+) \*/[ \t]*$", re.M)


class PatchError(ValueError):
    pass


def find_markers(text: str) -> list[tuple[str, int, int]]:
    """Return (name, content_start, content_end) for each marked block; validates pairing."""
    begins = [(m.group(1), m) for m in _BEGIN.finditer(text)]
    ends = {m.group(1): m for m in _END.finditer(text)}
    if len(ends) != len(list(_END.finditer(text))):
        raise PatchError("duplicate CALGEN:END marker")
    seen: set[str] = set()
    out = []
    for name, b in begins:
        if name in seen:
            raise PatchError(f"duplicate CALGEN:BEGIN {name}")
        seen.add(name)
        e = ends.get(name)
        if e is None or e.start() < b.end():
            raise PatchError(f"CALGEN:BEGIN {name} has no matching END after it")
        out.append((name, b.end(), e.start()))
    for name in ends:
        if name not in seen:
            raise PatchError(f"CALGEN:END {name} has no BEGIN")
    out.sort(key=lambda t: t[1])
    for (n1, _, e1), (n2, s2, _) in zip(out, out[1:]):
        if s2 < e1:
            raise PatchError(f"CALGEN blocks {n1} and {n2} overlap")
    return out


def patch(text: str, build: Build) -> str:
    """Rewrite the content of every marked block; everything outside markers is untouched."""
    secs = sections(build)
    markers = find_markers(text)
    unknown = [n for n, _, _ in markers if n not in build.rules.blocks]
    if unknown:
        raise PatchError(f"file has CALGEN blocks not defined in rules: {', '.join(unknown)}")
    out, pos = [], 0
    for name, start, end in markers:
        out.append(text[pos:start])
        body = secs.get(name, f"/* no constants for block {name} */")
        out.append(f"\n{body}\n")
        pos = end
    out.append(text[pos:])
    return "".join(out)

